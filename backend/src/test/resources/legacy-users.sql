CREATE TABLE app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP, name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(32) NOT NULL, phone VARCHAR(255), active BOOLEAN NOT NULL,
  approval_status VARCHAR(255) DEFAULT 'APPROVED' NOT NULL
);
