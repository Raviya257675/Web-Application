import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { notificationApi } from '../api';
import { useApi } from '../hooks/useApi';
import { useToast } from '../context/ToastContext.jsx';
import { Badge, Empty, ErrorState, Icon, Loader, PageHead, Tabs } from '../components/ui';
import { relative } from '../utils/format';

const TYPES = {
  APPOINTMENT: { icon: 'calendar', label: 'Appointment' },
  BILLING: { icon: 'receipt', label: 'Billing' },
  LAB: { icon: 'flask', label: 'Laboratory' },
  PHARMACY: { icon: 'pill', label: 'Pharmacy' },
  ADMISSION: { icon: 'bed', label: 'Admission' },
  SYSTEM: { icon: 'bell', label: 'System' },
};

export default function Notifications() {
  const toast = useToast();
  const navigate = useNavigate();
  const [tab, setTab] = useState('ALL');
  const { data, loading, error, refetch } = useApi(() => notificationApi.list(), []);
  const notifications = data || [];
  const unread = notifications.filter((item) => !item.read);

  const open = async (item) => {
    if (!item.read) {
      try {
        await notificationApi.markRead(item.id);
        refetch();
      } catch (err) {
        toast.error(err.message);
      }
    }
    if (item.link) navigate(item.link);
  };

  const markAll = async () => {
    try {
      await notificationApi.markAllRead();
      toast.success('All notifications marked as read');
      refetch();
    } catch (err) {
      toast.error(err.message);
    }
  };

  const filtered = tab === 'UNREAD' ? unread : notifications;

  return (
    <div className="page">
      <PageHead
        eyebrow="Inbox"
        title="Notifications"
        description="Appointment, billing, laboratory and admission updates generated by the hospital."
        actions={<button type="button" className="btn" onClick={markAll} disabled={unread.length === 0}><Icon name="check" size={15} /> Mark all read</button>}
      />

      <Tabs
        tabs={[{ value: 'ALL', label: 'All', count: notifications.length }, { value: 'UNREAD', label: 'Unread', count: unread.length }]}
        value={tab}
        onChange={setTab}
      />

      {loading ? <Loader label="Loading notifications…" /> : null}
      {error ? <ErrorState error={error} onRetry={refetch} /> : null}
      {!loading && !error && filtered.length === 0 ? <Empty icon="bell" title="Nothing here" message="You are all caught up." /> : null}

      <div className="stack stack--tight">
        {filtered.map((item) => {
          const meta = TYPES[item.type] || TYPES.SYSTEM;
          return (
            <button
              type="button"
              key={item.id}
              className={`card notif-row ${item.read ? '' : 'notif-row--unread'}`}
              onClick={() => open(item)}
            >
              <span className={`notif-row__icon notif-row__icon--${(item.type || 'SYSTEM').toLowerCase()}`}><Icon name={meta.icon} size={17} /></span>
              <span className="notif-row__body">
                <span className="notif-row__title">
                  <strong>{item.title}</strong>
                  {!item.read ? <Badge tone="info">New</Badge> : null}
                </span>
                <span className="notif-row__message">{item.message}</span>
                <span className="notif-row__meta">{meta.label} · {relative(item.createdAt)}{item.link ? ' · open →' : ''}</span>
              </span>
            </button>
          );
        })}
      </div>
    </div>
  );
}
